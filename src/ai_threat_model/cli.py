"""Command-line interface.

Exit codes:
    0  scan completed and no finding met ``--fail-on``
    1  scan completed and at least one finding met ``--fail-on``
    2  usage, scan, or report error (or interrupted)
"""

from __future__ import annotations

import argparse
import logging
import sys
from pathlib import Path
from typing import Sequence

from . import __version__
from .engine import ScanOptions, ScanStats, scan
from .errors import LLMError, ThreatModelError
from .logging_setup import configure_logging
from .models import Severity, ThreatModel
from .narrative import generate_narrative
from .ollama_client import (
    DEFAULT_MAX_RETRIES,
    DEFAULT_OLLAMA_MODEL,
    DEFAULT_OLLAMA_URL,
    DEFAULT_TIMEOUT_SECONDS,
    MAX_RETRIES_LIMIT,
    OllamaClient,
)
from .reporting import RENDERERS, write_reports

LOGGER = logging.getLogger(__name__)

EXIT_OK = 0
EXIT_FINDINGS = 1
EXIT_ERROR = 2


def _positive_int(text: str) -> int:
    try:
        value = int(text)
    except ValueError as error:
        raise argparse.ArgumentTypeError(f"expected an integer, got {text!r}") from error
    if value <= 0:
        raise argparse.ArgumentTypeError("must be greater than 0")
    return value


def _positive_float(text: str) -> float:
    try:
        value = float(text)
    except ValueError as error:
        raise argparse.ArgumentTypeError(f"expected a number, got {text!r}") from error
    if not 0 < value <= 3600:
        raise argparse.ArgumentTypeError("must be between 0 and 3600 seconds")
    return value


def _retry_count(text: str) -> int:
    try:
        value = int(text)
    except ValueError as error:
        raise argparse.ArgumentTypeError(f"expected an integer, got {text!r}") from error
    if not 0 <= value <= MAX_RETRIES_LIMIT:
        raise argparse.ArgumentTypeError(f"must be between 0 and {MAX_RETRIES_LIMIT}")
    return value


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="ai-threat-model",
        description="Build a threat model for a LangChain / LangGraph application by static analysis.",
    )
    parser.add_argument("path", type=Path, help="root directory of the application to scan")
    parser.add_argument("-o", "--output-dir", type=Path, default=Path("threat-model-report"),
                        help="directory for the reports (default: %(default)s)")
    parser.add_argument("-f", "--format", nargs="+", choices=sorted(RENDERERS), default=["md", "json"],
                        help="report formats (default: md json)")
    parser.add_argument("--fail-on", choices=["none", *(s.value for s in sorted(Severity, key=lambda s: s.rank))],
                        default="none", help="exit with code 1 if a finding of this severity or higher exists")
    parser.add_argument("--max-file-size", type=_positive_int, default=ScanOptions.max_file_bytes,
                        metavar="BYTES", help="skip files larger than this (default: %(default)s)")
    parser.add_argument("--max-files", type=_positive_int, default=ScanOptions.max_files,
                        help="maximum number of files to scan (default: %(default)s)")

    cache = parser.add_argument_group("incremental analysis")
    cache.add_argument("--cache-dir", type=Path,
                       help="save per-file results and function summaries here and reuse them for unchanged files")
    cache.add_argument("--rebuild-cache", action="store_true",
                       help="ignore the existing cache and write a fresh one (requires --cache-dir)")

    llm = parser.add_argument_group("optional AI narrative (local Ollama)")
    llm.add_argument("--llm", action="store_true", help="add an advisory narrative generated by a local Ollama model")
    llm.add_argument("--ollama-url", default=DEFAULT_OLLAMA_URL, help="Ollama base URL (default: %(default)s)")
    llm.add_argument("--ollama-model", default=DEFAULT_OLLAMA_MODEL, help="Ollama model (default: %(default)s)")
    llm.add_argument("--ollama-timeout", type=_positive_float, default=DEFAULT_TIMEOUT_SECONDS,
                     metavar="SECONDS", help="max seconds to wait for the first token or between tokens (default: %(default)s)")
    llm.add_argument("--ollama-retries", type=_retry_count, default=DEFAULT_MAX_RETRIES,
                     help=f"retries after a transient Ollama failure, 0-{MAX_RETRIES_LIMIT} (default: %(default)s)")
    llm.add_argument("--allow-remote-llm", action="store_true",
                     help="permit a non-loopback Ollama URL (scan results will leave this machine)")

    logs = parser.add_argument_group("logging")
    logs.add_argument("--log-level", default="WARNING",
                      choices=["DEBUG", "INFO", "WARNING", "ERROR"], help="console log level (default: %(default)s)")
    logs.add_argument("--log-file", type=Path, help="also write logs to this rotating file")
    parser.add_argument("--version", action="version", version=f"%(prog)s {__version__}")
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        configure_logging(args.log_level, args.log_file)
    except ThreatModelError as error:
        print(f"error: {error}", file=sys.stderr)
        return EXIT_ERROR

    try:
        return _run(args)
    except ThreatModelError as error:
        LOGGER.error("%s", error)
        return EXIT_ERROR
    except KeyboardInterrupt:
        LOGGER.error("Interrupted")
        return EXIT_ERROR
    except Exception:  # noqa: BLE001 - last-resort handler so users get a log entry, not a raw crash
        LOGGER.exception("Unexpected error; please report this with the log file")
        return EXIT_ERROR


def _run(args: argparse.Namespace) -> int:
    if args.rebuild_cache and args.cache_dir is None:
        raise ThreatModelError("--rebuild-cache requires --cache-dir")

    # Validate LLM settings before the (possibly long) scan so mistakes fail fast.
    client = None
    if args.llm:
        client = OllamaClient(
            base_url=args.ollama_url, model=args.ollama_model, timeout_seconds=args.ollama_timeout,
            max_retries=args.ollama_retries, allow_remote=args.allow_remote_llm,
        )

    options = ScanOptions(max_file_bytes=args.max_file_size, max_files=args.max_files,
                          cache_dir=args.cache_dir, rebuild_cache=args.rebuild_cache)
    result = scan(args.path, options)
    model = result.model

    if client is not None:
        try:
            generate_narrative(model, client)
        except LLMError as error:
            LOGGER.warning("AI narrative skipped: %s", error)
            model.errors.append(f"AI narrative skipped: {error}")

    written = write_reports(model, args.output_dir, args.format)
    _print_summary(model, written, result.stats)
    return EXIT_FINDINGS if _meets_threshold(model, args.fail_on) else EXIT_OK


def _meets_threshold(model: ThreatModel, fail_on: str) -> bool:
    if fail_on == "none":
        return False
    threshold = Severity(fail_on).rank
    return any(finding.severity.rank >= threshold for finding in model.findings)


def _print_summary(model: ThreatModel, written: list[Path], stats: ScanStats) -> None:
    counts = model.severity_counts()
    summary = ", ".join(f"{counts[s.value]} {s.value}" for s in sorted(Severity, key=lambda s: -s.rank))
    print(f"Scanned {len(model.scanned_files)} files ({', '.join(model.frameworks) or 'no AI framework detected'}).")
    print(f"Components: {len(model.components)}  Findings: {len(model.findings)} ({summary})")
    if stats.cache_file is not None:
        saved = "saved" if stats.cache_saved else "NOT saved (see log)"
        print(f"Cache: reused {stats.reused}, analyzed {stats.analyzed}; {saved} to {stats.cache_file}")
    if model.errors:
        print(f"Warnings: {len(model.errors)} (see report)")
    for path in written:
        print(f"Report: {path}")
