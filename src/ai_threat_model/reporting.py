"""Renders a :class:`ThreatModel` as Markdown, JSON, or SARIF 2.1.0.

All text that originates from the scanned project is escaped for the target
format (Markdown tables, Mermaid labels) so a malicious repository cannot
inject markup into the report.
"""

from __future__ import annotations

import json
import logging
import os
import re
import tempfile
from dataclasses import asdict
from enum import Enum
from pathlib import Path
from typing import Callable

from . import __version__
from .errors import ReportError
from .models import Component, ComponentKind, ControlStatus, Finding, Severity, ThreatModel
from .rules import OWASP_AGENTIC, RULES, agentic_label

LOGGER = logging.getLogger(__name__)

TOOL_NAME = "ai-threat-model"
MAX_DIAGRAM_NODES = 40

_KIND_TITLES = {
    ComponentKind.ENTRY_POINT: "Entry points",
    ComponentKind.MODEL: "Model calls",
    ComponentKind.AGENT: "Agents",
    ComponentKind.TOOL: "Tools",
    ComponentKind.RETRIEVAL: "Retrieval sources",
    ComponentKind.GRAPH_NODE: "LangGraph nodes",
    ComponentKind.MEMORY: "Memory and state",
    ComponentKind.OBSERVABILITY: "Observability",
}
_CONTROL_ICONS = {
    ControlStatus.PRESENT: "present",
    ControlStatus.PARTIAL: "partial",
    ControlStatus.MISSING: "**missing**",
    ControlStatus.NOT_APPLICABLE: "n/a",
}
_SARIF_LEVELS = {
    Severity.CRITICAL: "error", Severity.HIGH: "error", Severity.MEDIUM: "warning",
    Severity.LOW: "note", Severity.INFO: "note",
}
_SECURITY_SEVERITY = {
    Severity.CRITICAL: "9.5", Severity.HIGH: "8.0", Severity.MEDIUM: "5.5",
    Severity.LOW: "3.0", Severity.INFO: "1.0",
}


# --------------------------------------------------------------------------- helpers


def _cell(value: object) -> str:
    """Escape text for a Markdown table cell."""
    text = str(value).replace("\\", "\\\\").replace("|", "\\|").replace("`", "'")
    text = text.replace("<", "&lt;").replace(">", "&gt;")
    return " ".join(text.split())


def _inline(value: object) -> str:
    """Escape text for inline Markdown prose."""
    return str(value).replace("<", "&lt;").replace(">", "&gt;").replace("\r", " ")


def _mermaid_label(value: str) -> str:
    return re.sub(r"[^A-Za-z0-9 _.:/@()\-]", "", value)[:60] or "item"


# --------------------------------------------------------------------------- markdown


def render_markdown(model: ThreatModel) -> str:
    lines: list[str] = []
    out = lines.append
    counts = model.severity_counts()

    out("# AI Threat Model")
    out("")
    out(f"- **Project:** `{_cell(Path(model.project_root).name)}`")
    out(f"- **Generated:** {model.generated_at} by {TOOL_NAME} {__version__}")
    out(f"- **Frameworks:** {_cell(', '.join(model.frameworks) or 'none detected')}")
    out(f"- **Files scanned:** {len(model.scanned_files)}")
    out("")
    out("## Summary")
    out("")
    out("| Critical | High | Medium | Low | Info |")
    out("|---:|---:|---:|---:|---:|")
    out(f"| {counts['critical']} | {counts['high']} | {counts['medium']} | {counts['low']} | {counts['info']} |")
    out("")

    if model.llm_narrative:
        out(f"## AI-assisted analysis (advisory, generated by `{_cell(model.llm_model or 'LLM')}`)")
        out("")
        out("> This is an advisory summary, not a scanner finding or validation. LLM output can be inaccurate; "
            "verify every claim against the source and finding evidence below.")
        out("")
        out(model.llm_narrative)
        out("")

    out("## Architecture")
    out("")
    out(_mermaid(model))
    out("")

    out("## Trust boundaries")
    out("")
    if model.trust_boundaries:
        out("| ID | Boundary | From | To | Components | Why it matters |")
        out("|---|---|---|---|---:|---|")
        for b in model.trust_boundaries:
            out(f"| {b.id} | {_cell(b.name)} | {_cell(b.source_zone)} | {_cell(b.target_zone)} "
                f"| {len(b.component_ids)} | {_cell(b.description)} |")
    else:
        out("_No trust boundaries identified._")
    out("")

    out("## Inventory")
    out("")
    for kind, title in _KIND_TITLES.items():
        items = model.components_of(kind)
        if not items:
            continue
        out(f"### {title} ({len(items)})")
        out("")
        out("| Name | Location | Details |")
        out("|---|---|---|")
        for component in items:
            out(f"| {_cell(component.name)} | `{_cell(component.location)}` | {_details(component)} |")
        out("")

    out("## Findings")
    out("")
    if not model.findings:
        out("_No findings._")
        out("")
    for severity in sorted(Severity, key=lambda s: -s.rank):
        group = [f for f in model.findings if f.severity is severity]
        if not group:
            continue
        out(f"### {severity.value.title()} ({len(group)})")
        out("")
        for finding in group:
            lines.extend(_finding_markdown(finding))

    lines.extend(_owasp_agentic_markdown(model))
    lines.extend(_controls_markdown(model))

    if model.data_flows:
        names = {c.id: c.name for c in model.components}
        out("## Data flows")
        out("")
        out("| From | To | Data | Boundary |")
        out("|---|---|---|---|")
        for flow in model.data_flows[:200]:
            out(f"| {_cell(names.get(flow.source_id, flow.source_id))} | {_cell(names.get(flow.target_id, flow.target_id))} "
                f"| {_cell(flow.label)} | {flow.boundary_id or '-'} |")
        if len(model.data_flows) > 200:
            out(f"\n_{len(model.data_flows) - 200} more flows omitted (see JSON report)._")
        out("")

    if model.errors:
        out("## Scan warnings")
        out("")
        for error in model.errors:
            out(f"- {_inline(error)}")
        out("")

    out("## Methodology and limitations")
    out("")
    out("- Static AST analysis only; the scanned code is never imported or executed.")
    out("- Taint tracking is flow-insensitive within a function and follows calls between project "
        "functions through parameter/return summaries (interprocedural).")
    out("- Sanitizers and validation logic are not modeled, so some findings may be false positives; "
        "dynamic dispatch, reflection, and framework magic may cause false negatives.")
    out("- Personal data is recognized by identifier names; authentication detection is heuristic.")
    out("- Runtime-only agentic risks (goal hijack in a live session, rogue behavior, cascading failures, "
        "object-level authorization such as IDOR) cannot be proven statically; the controls checklist "
        "reports the evidence that defenses exist, not that they are effective.")
    out("- Secret values are masked in this report.")
    out("")
    return "\n".join(lines)


def _details(component: Component) -> str:
    return _cell("; ".join(f"{k}: {v}" for k, v in sorted(component.attributes.items()) if v)) or "-"


def _finding_markdown(finding: Finding) -> list[str]:
    lines = [
        f"#### [{finding.rule_id}] {_inline(finding.title)}",
        "",
        f"- **Location:** `{_cell(finding.location)}`",
        f"- **Category:** {_inline(finding.category)}",
        f"- **Confidence:** {finding.confidence}",
    ]
    if finding.owasp_agentic:
        lines.append(f"- **OWASP Agentic:** {_inline(', '.join(agentic_label(code) for code in finding.owasp_agentic))}")
    if finding.location.snippet:
        lines.append(f"- **Code:** `{_cell(finding.location.snippet)}`")
    lines.append("")
    lines.append(_inline(finding.description))
    lines.append("")
    if finding.related:
        lines.append("Related locations:")
        lines.extend(f"- `{_cell(location)}`" for location in finding.related[:10])
        lines.append("")
    lines.append(f"**Recommendation:** {_inline(finding.recommendation)}")
    lines.append("")
    return lines


def _owasp_agentic_markdown(model: ThreatModel) -> list[str]:
    """Coverage table: each OWASP Agentic risk with its findings and related controls."""
    lines = ["## OWASP Top 10 for Agentic Applications", "",
             "| Risk | Findings | Rules | Controls |", "|---|---:|---|---|"]
    for code, name in OWASP_AGENTIC.items():
        findings = [f for f in model.findings if code in f.owasp_agentic]
        rule_ids = sorted({f.rule_id for f in findings})
        controls = [c for c in model.controls if code in c.owasp_agentic and c.status is not ControlStatus.NOT_APPLICABLE]
        control_text = ", ".join(f"{c.id} {_CONTROL_ICONS[c.status]}" for c in controls) or "-"
        lines.append(f"| {code} {_cell(name)} | {len(findings)} | {_cell(', '.join(rule_ids)) or '-'} | {control_text} |")
    lines.append("")
    lines.append("_Zero findings does not mean a risk is absent: goal hijack, rogue agents and cascading "
                 "failures are largely runtime behaviors. Use the controls column as a review guide._")
    lines.append("")
    return lines


def _controls_markdown(model: ThreatModel) -> list[str]:
    """Checklist of agent defenses with their statically observed evidence."""
    if not model.controls:
        return []
    lines = ["## Agent controls checklist", "",
             "| ID | Control | Status | OWASP | Notes | Evidence |", "|---|---|---|---|---|---|"]
    for control in model.controls:
        evidence = ", ".join(f"`{_cell(location)}`" for location in control.evidence[:3]) or "-"
        if len(control.evidence) > 3:
            evidence += f" (+{len(control.evidence) - 3})"
        lines.append(f"| {control.id} | {_cell(control.name)} | {_CONTROL_ICONS[control.status]} "
                     f"| {', '.join(control.owasp_agentic)} | {_cell(control.note)} | {evidence} |")
    lines.append("")
    return lines


def _mermaid(model: ThreatModel) -> str:
    """Architecture diagram grouped by trust zone, capped to keep it readable."""
    zones = [
        (ComponentKind.ENTRY_POINT, "Users / clients"),
        (ComponentKind.AGENT, "Application"),
        (ComponentKind.MODEL, "Model providers"),
        (ComponentKind.TOOL, "Tools and downstream systems"),
        (ComponentKind.RETRIEVAL, "Untrusted content and data stores"),
        (ComponentKind.MEMORY, "Memory and state"),
        (ComponentKind.OBSERVABILITY, "Observability vendors"),
    ]
    ids: dict[str, str] = {}
    lines = ["```mermaid", "flowchart LR"]
    for index, (kind, title) in enumerate(zones):
        members = model.components_of(kind)[: MAX_DIAGRAM_NODES // len(zones)]
        if not members:
            continue
        lines.append(f'  subgraph Z{index}["{title}"]')
        for component in members:
            node_id = f"N{len(ids)}"
            ids[component.id] = node_id
            lines.append(f'    {node_id}["{_mermaid_label(component.name)}"]')
        lines.append("  end")
    seen: set[tuple[str, str]] = set()
    for flow in model.data_flows:
        pair = (ids.get(flow.source_id, ""), ids.get(flow.target_id, ""))
        if all(pair) and pair not in seen:
            seen.add(pair)
            lines.append(f'  {pair[0]} -->|"{_mermaid_label(flow.label)}"| {pair[1]}')
    if not ids:
        lines.append('  empty["No AI components detected"]')
    lines.append("```")
    return "\n".join(lines)


# --------------------------------------------------------------------------- json / sarif


def _json_default(value: object) -> object:
    if isinstance(value, Enum):
        return value.value
    raise TypeError(f"Unserializable type {type(value).__name__}")


def render_json(model: ThreatModel) -> str:
    data = asdict(model)
    data["tool"] = {"name": TOOL_NAME, "version": __version__}
    data["severity_counts"] = model.severity_counts()
    for component, raw in zip(model.components, data["components"]):
        raw["id"] = component.id
    return json.dumps(data, indent=2, default=_json_default)


def render_sarif(model: ThreatModel) -> str:
    used_rules = sorted({finding.rule_id for finding in model.findings})
    rule_index = {rule_id: index for index, rule_id in enumerate(used_rules)}
    rules = []
    for rule_id in used_rules:
        rule = RULES[rule_id]
        rules.append({
            "id": rule.id,
            "name": re.sub(r"[^A-Za-z0-9]", "", rule.title.title()),
            "shortDescription": {"text": rule.title},
            "help": {"text": rule.recommendation},
            "properties": {
                "tags": ["security", "ai", rule.category, *rule.owasp_agentic],
                "security-severity": _SECURITY_SEVERITY[rule.severity],
            },
        })
    results = []
    for finding in model.findings:
        results.append({
            "ruleId": finding.rule_id,
            "ruleIndex": rule_index[finding.rule_id],
            "level": _SARIF_LEVELS[finding.severity],
            "message": {"text": f"{finding.title}: {finding.description}"},
            "locations": [_sarif_location(finding.location.file, finding.location.line)],
            "relatedLocations": [
                {"id": i, **_sarif_location(loc.file, loc.line)} for i, loc in enumerate(finding.related[:10])
            ],
            "properties": {
                "severity": finding.severity.value,
                "confidence": finding.confidence,
                "security-severity": _SECURITY_SEVERITY[finding.severity],
                "owasp-agentic": list(finding.owasp_agentic),
            },
        })
    sarif = {
        "$schema": "https://json.schemastore.org/sarif-2.1.0.json",
        "version": "2.1.0",
        "runs": [{
            "tool": {"driver": {"name": TOOL_NAME, "version": __version__, "rules": rules}},
            "results": results,
        }],
    }
    return json.dumps(sarif, indent=2)


def _sarif_location(file: str, line: int) -> dict[str, object]:
    return {"physicalLocation": {
        "artifactLocation": {"uri": file},
        "region": {"startLine": max(1, line)},
    }}


# --------------------------------------------------------------------------- writing

RENDERERS: dict[str, tuple[str, Callable[[ThreatModel], str]]] = {
    "md": ("threat-model.md", render_markdown),
    "json": ("threat-model.json", render_json),
    "sarif": ("threat-model.sarif", render_sarif),
}


def write_reports(model: ThreatModel, output_dir: Path, formats: list[str]) -> list[Path]:
    """Render and atomically write each requested format; return the written paths.

    Raises:
        ReportError: If a format is unknown or a file cannot be written.
    """
    try:
        output_dir.mkdir(parents=True, exist_ok=True)
    except OSError as error:
        raise ReportError(f"Cannot create output directory {output_dir}: {error.strerror}") from error
    written: list[Path] = []
    for fmt in dict.fromkeys(formats):
        if fmt not in RENDERERS:
            raise ReportError(f"Unknown report format: {fmt}")
        filename, renderer = RENDERERS[fmt]
        target = output_dir / filename
        _atomic_write(target, renderer(model))
        LOGGER.info("Wrote %s", target)
        written.append(target)
    return written


def _atomic_write(target: Path, content: str) -> None:
    temp_name = ""
    try:
        with tempfile.NamedTemporaryFile(
            "w", encoding="utf-8", newline="\n", dir=target.parent, prefix=f".{target.name}.", delete=False,
        ) as handle:
            temp_name = handle.name
            handle.write(content)
        os.replace(temp_name, target)
    except OSError as error:
        if temp_name:
            try:
                os.unlink(temp_name)
            except OSError:
                LOGGER.debug("Could not remove temporary file %s", temp_name)
        raise ReportError(f"Cannot write {target}: {error.strerror or error}") from error
